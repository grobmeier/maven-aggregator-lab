"""One authoritative registry for cases, sets, comparisons, and reference text."""

from site_render import site_metadata
from cases import ordering
from cases import failure
from cases import selection
from cases import inheritance
from cases import site
import re

# Family registration is explicit. No filesystem or plugin discovery occurs.
CASES = sorted([*ordering.CASES, *failure.CASES, *selection.CASES,
                *inheritance.CASES, *site.CASES], key=lambda case: case.order)
GROUPS = tuple(dict.fromkeys(case.group for case in CASES))


def named_sets(cases):
    return tuple(dict.fromkeys(("all", *(case.group for case in cases), *(name for case in cases for name in case.sets))))


SETS = named_sets(CASES)
COMPARISONS = [(case.name, peer, label) for case in CASES for peer, label in case.comparisons]


def validate(cases=CASES):
    from fixtures import BUILDERS
    from assessment import EVALUATORS
    names = [case.name for case in cases]
    if len(names) != len(set(names)):
        raise ValueError("Case IDs must be unique.")
    for case in cases:
        if not re.fullmatch(r"[a-z0-9-]+", case.name):
            raise ValueError("Case IDs must contain lowercase letters, digits, or hyphens.")
        if case.threads < 1 or case.contract_version < 1:
            raise ValueError("Worker counts and contract versions must be positive.")
        if case.requirement_policy not in {"ordered", "observation", "failure_safety", "success_only", "rendered_site"}:
            raise ValueError("Select a registered requirement policy.")
        if case.fixture_kind not in BUILDERS or case.assessment_kind not in EVALUATORS:
            raise ValueError("Select registered fixture and assessment handlers.")
        for peer, label in case.comparisons:
            if peer not in names or peer == case.name or not label:
                raise ValueError("Each comparison must reference another registered case.")


def select_cases(names=(), groups=(), sets=()):
    """Combine named cases and sets, then apply the group filter."""
    for values, allowed, label in ((names, {case.name for case in CASES}, "case"),
                                    (groups, set(GROUPS), "group"), (sets, set(SETS), "set")):
        unknown = set(values or ()) - allowed
        if unknown:
            raise ValueError(f"Unknown {label}: {', '.join(sorted(unknown))}")
    selected = [case for case in CASES if (not names and not sets) or case.name in (names or ())
                or any(name == "all" or name == case.group or name in case.sets for name in (sets or ()))]
    return [case for case in selected if not groups or case.group in groups]


def comparisons_for(case):
    return [(right if left == case.name else left, label)
            for left, right, label in COMPARISONS if case.name in (left, right)]


def reference_markdown():
    """Generate the case reference from registered definitions."""
    lines = ["# Acceptance case reference", "", "Generated by `./acceptance-suite.sh reference`. Do not edit this file manually.",
             "", "Use `./acceptance-suite.sh show CASE` to inspect evidence and execution details.",
             "", "Sets: " + ", ".join(f"`{name}`" for name in SETS) + ".",
             "The smoke set covers sequential, concurrent, and standalone ordering."]
    for group in GROUPS:
        lines += ["", f"## {group.capitalize()}", "", "| Case | Purpose | Policy |", "|---|---|---|"]
        for case in select_cases(groups=[group]):
            lines.append(f"| `{case.name}` | {case.purpose} | `{case.requirement_policy}` |")
    return "\n".join(lines) + "\n"


def case_metadata(case):
    if case.fixture_kind == "site":
        return {**site_metadata(), "case": case.name, "group": case.group,
                "fixture_kind": case.fixture_kind, "assessment_kind": case.assessment_kind,
                "requirement_policy": case.requirement_policy, "sets": list(case.sets)}
    intended = case.requirement
    return {"case": case.name, "purpose": case.purpose, "builder": case.builder, "threads": case.threads,
            "start_binding": "before:site" if case.lifecycle == "site" else "before:all",
            "end_binding": case.phase, "lifecycle": case.lifecycle, "selection": case.selection,
            "single_project": case.single, "nested_group": case.nested, "contributor_policy": case.contributors,
            "expectation": case.expectation, "intended_requirement": intended,
            "group": case.group, "requirement_policy": case.requirement_policy,
            "fixture_kind": case.fixture_kind, "assessment_kind": case.assessment_kind,
            "sets": list(case.sets), "limitations": list(case.limitations),
            "expected_diagnostic": {
                "success": "Ordered hooks and matching ZIP contents in this bounded fixture.",
                "early": "Reproduce the exact missing-contribution failure before child output exists.",
                "missing-b": "Reproduce the exact missing-b failure from the fixed contributor list.",
                "child-failure": "Reproduce child failure and end-attempt cleanup, without a ZIP or end-success marker.",
                "false-success": "Expose a valid ZIP and end-success marker despite a failed verification lifecycle.",
                "no-root": "Expose the absence of root hooks while selected child a completes.",
                "timing-diagnostic": "Check either an ordered successful trace or an exact early-output diagnostic. No barrier claim.",
                "inherited-copies": "Count exactly three start and finish executions: root, a, and b.",
                "explicit-copies": "Count exactly two start and finish executions: root and explicitly configured child a.",
            }[case.expectation]}

validate()
